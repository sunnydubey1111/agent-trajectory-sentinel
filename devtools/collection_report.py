"""Generate the corpus collection report from the corpora themselves.

The report is derived entirely from the corpora here, so it cannot drift from
the data: corpus sizes, class balance, acceptance rates and rejection reasons
all come from `manifest.json` / `rejected.json`. The "before" column is the
one exception — it is read out of git at `BASELINE_REV`, the revision that
predates the corpus re-collection.

    py -m devtools.collection_report > _internal/verification/COLLECTION_REPORT.md
"""
from __future__ import annotations

import collections
import functools
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TRACES = REPO_ROOT / "traces"
# The revision predating the corpus re-collection. It was dropped when the
# history was squashed, so the before/after comparison cannot currently be
# produced; `_baseline_available` detects that and the report says so rather
# than printing an empty column that reads as "there was nothing before".
BASELINE_REV = "dd3880f"

RECOLLECTED = ["langgraph7b", "autogen7b", "langgraph", "autogen",
               "ollama7b", "ollama", "real"]
PRUNED = ["real_research7b", "real_research3b", "real_ollama7b"]


def _load(path: Path) -> list[dict]:
    return json.loads(path.read_text("utf-8")) if path.exists() else []


@functools.cache
def _baseline_available() -> bool:
    """True when `BASELINE_REV` resolves in this checkout."""
    proc = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", f"{BASELINE_REV}^{{commit}}"],
        cwd=REPO_ROOT, capture_output=True, text=True)
    return proc.returncode == 0


def _old_manifest(corpus: str) -> list[dict]:
    if not _baseline_available():
        return []
    try:
        out = subprocess.run(
            ["git", "show", f"{BASELINE_REV}:traces/{corpus}/manifest.json"],
            cwd=REPO_ROOT, capture_output=True, text=True, check=True)
        return json.loads(out.stdout)
    except Exception:      # noqa: BLE001 - corpus absent at that revision
        return []


def _rejections(corpus: str) -> list[dict]:
    out = []
    for name in ("rejected.json", "rejected_expand.json"):
        out.extend(_load(TRACES / corpus / name))
    return out


def _reason(entry: dict) -> str:
    return entry["reason"].split(":")[0].split("(")[0].strip()


def main() -> int:
    have_baseline = _baseline_available()
    print("# Collection and label validity: corpus report\n")
    print("Generated by `py -m devtools.collection_report`; every number is read "
          "from the corpora, and the *before* column from git "
          f"`{BASELINE_REV}` (the revision predating re-collection).\n")
    if not have_baseline:
        warning = (
            f"> **The *before* column is unavailable.** `{BASELINE_REV}` does "
            "not resolve in this checkout: the revision was dropped when the "
            "history was squashed, and it is not reachable from any ref. The "
            "before/after comparison cannot be regenerated until that object "
            "is restored; `n/a` below means *not measurable here*, not *zero*."
        )
        print(warning + "\n")
        print(warning, file=sys.stderr)

    print("## Corpora re-collected under the v5 contract\n")
    print("| corpus | before | after | healthy | positives | attempts | "
          "accept rate |")
    print("|---|---:|---:|---:|---:|---:|---:|")
    for corpus in RECOLLECTED:
        new = _load(TRACES / corpus / "manifest.json")
        old = _old_manifest(corpus)
        rejected = _rejections(corpus)
        healthy = sum(1 for e in new if not e.get("failure_class"))
        positives = len(new) - healthy
        attempts = len(new) + len(rejected)
        rate = f"{100 * len(new) / attempts:.0f}%" if attempts else "-"
        before = len(old) if old else ("-" if have_baseline else "n/a")
        print(f"| {corpus} | {before} | {len(new)} | {healthy} | "
              f"{positives} | {attempts} | {rate} |")

    print("\n## Why episodes were rejected\n")
    print("Rejections are recorded per corpus in `rejected.json`; nothing is "
          "dropped silently.\n")
    print("| corpus | too short | injection never applied | other |")
    print("|---|---:|---:|---:|")
    for corpus in RECOLLECTED:
        counts = collections.Counter(_reason(r) for r in _rejections(corpus))
        other = sum(v for k, v in counts.items()
                    if k not in ("too short", "injection never applied"))
        print(f"| {corpus} | {counts.get('too short', 0)} | "
              f"{counts.get('injection never applied', 0)} | {other} |")

    print("\n## Corpora kept, with invalid labels retired\n")
    print("These corpora were sound apart from a few positives whose injector "
          "never fired. `devtools/prune_invalid_labels` applied the same gate "
          "retroactively: the episodes left `manifest.json` and are recorded "
          "in `rejected.json`. Their trace files are kept as provenance.\n")
    print("| corpus | episodes | retired |")
    print("|---|---:|---:|")
    for corpus in PRUNED:
        new = _load(TRACES / corpus / "manifest.json")
        retired = [r for r in _rejections(corpus)
                   if "retroactive" in r.get("reason", "")]
        print(f"| {corpus} | {len(new)} | {len(retired)} |")

    print("\n## Episode length against the monitor's washout\n")
    print("The ESN washout is 3 steps, so an episode needs T >= 4 to produce "
          "any score at all. The acceptance gate enforces that; the corpora "
          "collected before it did not.\n")
    print("| corpus | before: T<4 | after: T<4 |")
    print("|---|---:|---:|")
    for corpus in RECOLLECTED:
        old = _old_manifest(corpus)
        new = _load(TRACES / corpus / "manifest.json")
        old_short = sum(1 for e in old if e.get("T", 0) < 4)
        new_short = sum(1 for e in new if e.get("T", 0) < 4)
        if old:
            old_txt = f"{old_short}/{len(old)}"
        else:
            old_txt = "-" if have_baseline else "n/a"
        print(f"| {corpus} | {old_txt} | {new_short}/{len(new)} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
